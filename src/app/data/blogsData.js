export function getBlogById(id) {
  if (!id) return null;
  return blogPosts.find((blog) => String(blog.id) === String(id) || blog._id === id);
}

export function getBlogBySlug(slug) {
  if (!slug) return null;
  const decoded = decodeURIComponent(slug).toLowerCase();
  return blogPosts.find(
    (blog) =>
      blog.slug?.toLowerCase() === decoded ||
      String(blog.id).toLowerCase() === decoded ||
      blog._id?.toLowerCase() === decoded
  );
}
